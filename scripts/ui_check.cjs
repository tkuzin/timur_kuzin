const { chromium } = require(process.env.CODEX_NODE_MODULES + '/playwright');
const fs = require('fs');
(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  const page = await browser.newPage({viewport: {width: 1360, height: 980}, deviceScaleFactor: 1});
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  await page.goto('http://127.0.0.1:8080/login');
  await page.locator('[name=username]').fill('operator');
  await page.locator('[name=password]').fill('timur-demo-2026');
  await page.getByRole('button', {name: 'Войти', exact: true}).click();
  await page.locator('#rows tbody tr').first().waitFor();
  fs.mkdirSync('artifacts/screenshots', {recursive:true});
  await page.screenshot({path:'artifacts/screenshots/list.png', fullPage:true});
  await page.goto('http://127.0.0.1:8080/tickets/1');
  await page.getByRole('heading', {name: 'Переписка', exact:true}).waitFor();
  await page.screenshot({path:'artifacts/screenshots/detail.png', fullPage:true});
  await page.goto('http://127.0.0.1:8080/summary');
  await page.locator('tbody tr').last().waitFor();
  await page.screenshot({path:'artifacts/screenshots/summary.png', fullPage:true});
  // Complete the main workflow through the real browser.
  await page.goto('http://127.0.0.1:8080/');
  await page.locator('#rows tbody tr').first().waitFor();
  await page.locator('details summary').click();
  await page.locator('[name=title]').fill('Проверка сценария в браузере');
  await page.locator('[name=body]').fill('Контроль прохождения основной операции через интерфейс.');
  await page.getByRole('button', {name:'Отправить заявку'}).click();
  await page.getByRole('button', {name:'Взять в работу'}).click();
  await page.getByRole('button', {name:'Закрыть заявку'}).waitFor();
  await page.locator('#comment textarea').fill('Сотрудник ответил на обращение.');
  await page.getByRole('button', {name:'Добавить комментарий'}).click();
  await page.getByText('Сотрудник ответил на обращение.', {exact:true}).waitFor();
  await page.getByRole('button', {name:'Закрыть заявку'}).click();
  await page.getByText('Заявка закрыта.', {exact:true}).waitFor();
  await page.screenshot({path:'artifacts/screenshots/workflow.png', fullPage:true});
  fs.writeFileSync('artifacts/ui_check.json', JSON.stringify({ok:errors.length===0,errors,url:page.url(),checked:['login','list','detail','summary','create','in_progress','reply','closed']},null,2));
  console.log(JSON.stringify({errors,workflow:page.url()}));
  await browser.close();
  if(errors.length) process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
